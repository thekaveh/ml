def classify_network_checks(
    event_name: str, changed_paths: Sequence[str] | None
) -> NetworkCheckScope:
    """Select network checks, failing closed when change scope is not trustworthy."""

    if event_name in {"schedule", "workflow_dispatch"}:
        return NetworkCheckScope(True, True)
    if event_name not in {"pull_request", "push"} or not changed_paths:
        return NetworkCheckScope(True, True)
    paths = tuple(changed_paths)
    if any(
        not path
        or Path(path).is_absolute()
        or ".." in Path(path).parts
        or "\\" in path
        for path in paths
    ):
        return NetworkCheckScope(True, True)

    lock_check = False
    image_check = False
    for path in paths:
        if path in _BOTH_PATHS:
            lock_check = True
            image_check = True
        if (
            path in _DEPENDENCY_PATHS
            or path.startswith("requirements/locks/")
            or path.startswith(".github/workflows/")
        ):
            lock_check = True
        if path in _IMAGE_PATHS:
            image_check = True
    return NetworkCheckScope(lock_check, image_check)


def _documentation_findings(repo: Path) -> list[LockFinding]:
    findings: list[LockFinding] = []
    for path, required in _DOCUMENTATION_CONTRACT.items():
        try:
            source = (repo / path).read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            findings.append(_finding("documentation", path, "missing"))
            continue
        current = source.split("## [0.1.0]", 1)[0] if path == Path("CHANGELOG.md") else source
        if any(fragment not in current for fragment in required):
            findings.append(_finding("documentation", path, "required lock contract"))
            continue
        if any(fragment in current for fragment in _FORBIDDEN_CURRENT_DOCUMENTATION):
            findings.append(_finding("documentation", path, "stale install contract"))
    return findings


def _changed_paths(repo: Path, base: str, head: str) -> tuple[str, ...] | None:
    if not _FULL_SHA.fullmatch(base) or not _FULL_SHA.fullmatch(head):
        return None
    try:
        completed = subprocess.run(
            ("git", "diff", "--name-only", "--no-renames", f"{base}...{head}"),
            cwd=repo,
            text=True,
            capture_output=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if completed.returncode != 0:
        return None
    return tuple(completed.stdout.splitlines())


def _write_scope(path: Path, scope: NetworkCheckScope) -> None:
    with path.open("a", encoding="utf-8") as stream:
        stream.write(f"lock-check={str(scope.lock_check).lower()}\n")
        stream.write(f"image-check={str(scope.image_check).lower()}\n")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _target_for(platform: object) -> TargetEnvironment:
    values = dict(platform.marker_environment)
    values.update(
        {
            "implementation_version": "3.11.0",
            "python_full_version": "3.11.0",
            "extra": "",
        }
    )
    return TargetEnvironment(key=platform.key, marker_environment=values)


def _expected_header(repo: Path, policy: object, target: str) -> tuple[str, ...]:
    lines = (
        _GENERATOR_LINE,
        f"# policy-sha256: {_sha256(repo / 'requirements/lock-policy.toml')}",
        f"# target: {target}",
    )
    inputs = tuple(
        f"# input-sha256: {relative.as_posix()}={_sha256(repo / relative)}"
        for relative in policy.inputs
    )
    return lines + inputs


def _finding(category: str, relative: Path, detail: str) -> LockFinding:
    return LockFinding(category, relative.as_posix(), detail)


def _requirements_by_name(
    requirements: Sequence[LockedRequirement], target: TargetEnvironment | None = None
) -> dict[str, LockedRequirement]:
    selected = requirements if target is None else project_for_target(requirements, target)
    return {requirement.name: requirement for requirement in selected}


def _target_name(relative: Path) -> str:
    parts = relative.parts
    if len(parts) >= 4 and parts[:2] == ("requirements", "locks"):
        return parts[2]
    return "supported-matrix"


