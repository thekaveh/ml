def verify_dependency_locks(repo: Path) -> tuple[LockFinding, ...]:
    try:
        policy = load_policy(repo)
    except DependencyLockError:
        return (LockFinding("policy", "requirements/lock-policy.toml", "invalid"),)
    findings: list[LockFinding] = []
    parsed: dict[Path, tuple[LockedRequirement, ...]] = {}
    for relative in policy.outputs:
        path = repo / relative
        if not path.is_file():
            findings.append(LockFinding("inventory", relative.as_posix(), "missing"))
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            findings.append(_finding("content", relative, "unreadable"))
            continue
        if any(
            token in text
            for token in (
                "/private/",
                "/Users/",
                "file:",
                "git+",
                "--extra-index-url",
                "${",
                "$(",
                "`",
            )
        ):
            findings.append(_finding("content", relative, "unsafe"))
            continue
        lines = tuple(text.splitlines())
        expected_header = _expected_header(repo, policy, _target_name(relative))
        if lines[: len(expected_header)] != expected_header:
            findings.append(_finding("header", relative, "drift"))
            continue
        try:
            requirements = parse_lock(path)
        except DependencyLockError:
            findings.append(_finding("content", relative, "invalid"))
            continue
        if not requirements:
            findings.append(_finding("content", relative, "empty"))
            continue
        parsed[relative] = requirements
    if findings:
        return tuple(findings)

    bootstrap = _requirements_by_name(parsed[Path("requirements/locks/bootstrap.txt")])
    compiler = _requirements_by_name(parsed[Path("requirements/locks/compiler.txt")])
    atlas = _requirements_by_name(parsed[Path("requirements/locks/atlas-contract.txt")])
    expected_bootstrap = {
        "pip": Version("26.1.2"),
        "setuptools": Version("81.0.0"),
        "wheel": Version("0.47.0"),
        "packaging": Version("26.2"),
    }
    if {name: item.version for name, item in bootstrap.items()} != expected_bootstrap:
        findings.append(_finding("pin", Path("requirements/locks/bootstrap.txt"), "bootstrap"))
    if {name: item.version for name, item in compiler.items()} != {"uv": Version("0.11.19")}:
        findings.append(_finding("pin", Path("requirements/locks/compiler.txt"), "compiler"))
    atlas_direct = {"pytest": Version("9.0.3"), "pyyaml": Version("6.0.3"), "uv": Version("0.11.19")}
    if any(atlas.get(name) is None or atlas[name].version != version for name, version in atlas_direct.items()):
        findings.append(_finding("pin", Path("requirements/locks/atlas-contract.txt"), "Atlas"))

    docs_requirements = parsed[Path("docs-requirements.txt")]
    for platform in policy.platforms:
        target = _target_for(platform)
        root_path = Path("requirements/locks") / platform.key / "root.txt"
        runtime_path = Path("requirements/locks") / platform.key / "runtime.txt"
        core_path = Path("requirements/locks") / platform.key / "core.txt"
        root = _requirements_by_name(parsed[root_path])
        runtime = _requirements_by_name(parsed[runtime_path])
        core = _requirements_by_name(parsed[core_path])
        docs = _requirements_by_name(docs_requirements, target)
        if not set(core) <= set(runtime) or not set(runtime) <= set(root):
            findings.append(_finding("subset", runtime_path, "core-runtime-root"))
        if not set(bootstrap) <= set(root) or not set(docs) <= set(root):
            findings.append(_finding("subset", root_path, "bootstrap-docs-root"))
        local = "" if platform.system == "Darwin" else "+cpu"
        expected_core = {
            "torch": Version(f"2.11.0{local}"),
            "torchvision": Version(f"0.26.0{local}"),
            "torchaudio": Version(f"2.11.0{local}"),
        }
        if any(
            core.get(name) is None or core[name].version != version
            for name, version in expected_core.items()
        ):
            findings.append(_finding("pin", core_path, "Torch"))
        pyg_local = "+pt211" if platform.system == "Darwin" else "+pt211cpu"
        expected_runtime = {
            "pyg-lib": Version(f"0.8.0{pyg_local}"),
            "torch-scatter": Version(
                "2.1.2" if platform.system == "Darwin" else "2.1.2+pt211cpu"
            ),
            "torch-sparse": Version(
                "0.6.18" if platform.system == "Darwin" else "0.6.18+pt211cpu"
            ),
            "torch-geometric": Version("2.8.0.post1"),
            "torchao": Version(
                "0.18.0" if platform.system == "Darwin" else "0.18.0+cpu"
            ),
        }
        if any(
            runtime.get(name) is None or runtime[name].version != version
            for name, version in expected_runtime.items()
        ):
            findings.append(_finding("pin", runtime_path, "runtime"))
        direct = [requirement for requirement in root.values() if requirement.source is not None]
        if (
            len(direct) != 1
            or direct[0].name != "en-core-web-sm"
            or direct[0].source != _MODEL_URL
            or direct[0].hashes != (_MODEL_HASH,)
        ):
            findings.append(_finding("source", root_path, "NLP model"))
        if root.get("python-louvain") is None or root["python-louvain"].version != Version("0.16"):
            findings.append(_finding("pin", root_path, "python-louvain"))
    findings.extend(_consumer_findings(repo))
    findings.extend(_documentation_findings(repo))
    return tuple(findings)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    parser.add_argument("--classify-event")
    parser.add_argument("--base")
    parser.add_argument("--head")
    parser.add_argument("--github-output", type=Path)
    arguments = parser.parse_args(argv)
    repo = arguments.repo_root.resolve()
    if arguments.classify_event is not None:
        paths = None
        if arguments.classify_event in {"schedule", "workflow_dispatch"}:
            paths = ()
        elif arguments.base is not None and arguments.head is not None:
            paths = _changed_paths(repo, arguments.base, arguments.head)
        scope = classify_network_checks(arguments.classify_event, paths)
        if arguments.github_output is None:
            parser.error("--github-output is required with --classify-event")
        _write_scope(arguments.github_output, scope)
        return 0
    if any(
        value is not None
        for value in (arguments.base, arguments.head, arguments.github_output)
    ):
        parser.error("classification arguments require --classify-event")
    findings = verify_dependency_locks(repo)
    if findings:
        for finding in findings:
            print(
                f"dependency lock verification failed: {finding.category}: {finding.path}",
                file=sys.stderr,
            )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
